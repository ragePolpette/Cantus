import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";
import { analyze, exportClaudeAgents, migrateLegacyDir, NOTES_START, writeNotes } from "../dist/index.js";
import { copyFixture, shopModel } from "./helpers.mjs";

const cli = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "dist", "cli.js");

// Projects mapped while Cantus was called ArchFlow keep their map, notes and specialists.

test("the first command moves .archflow/ to .cantus/, with the .gitignore entries", () => {
  const root = copyFixture("shop");
  fs.mkdirSync(path.join(root, ".archflow", "cache"), { recursive: true });
  fs.writeFileSync(path.join(root, ".archflow", "model.json"), JSON.stringify({ ...shopModel(), name: "Shop from before" }, null, 2));
  fs.writeFileSync(path.join(root, ".gitignore"), "node_modules/\n.archflow/cache/\n**/.archflow/*.log\n.archflowish\n");

  const result = spawnSync(process.execPath, [cli, "check", "-C", root, "--json"], { encoding: "utf8" });
  assert.match(result.stderr, /moved \.archflow\/ → \.cantus\/, \.gitignore/);
  assert.doesNotThrow(() => JSON.parse(result.stdout), "stdout stays machine-readable");
  assert.ok(!fs.existsSync(path.join(root, ".archflow")));
  assert.equal(JSON.parse(fs.readFileSync(path.join(root, ".cantus", "model.json"), "utf8")).name, "Shop from before");
  assert.equal(fs.readFileSync(path.join(root, ".gitignore"), "utf8"), "node_modules/\n.cantus/cache/\n**/.cantus/*.log\n.archflowish\n");

  const again = spawnSync(process.execPath, [cli, "check", "-C", root], { encoding: "utf8" });
  assert.doesNotMatch(again.stderr, /moved/, "only once");
});

test("an existing .cantus/ is never overwritten by an old .archflow/", () => {
  const root = copyFixture("shop");
  fs.mkdirSync(path.join(root, ".archflow"));
  fs.mkdirSync(path.join(root, ".cantus"));
  fs.writeFileSync(path.join(root, ".cantus", "model.json"), "new");
  assert.deepEqual(migrateLegacyDir(root), []);
  assert.equal(fs.readFileSync(path.join(root, ".cantus", "model.json"), "utf8"), "new");
  assert.ok(fs.existsSync(path.join(root, ".archflow")));
});

test("notes between the old archflow markers are replaced, not duplicated", () => {
  const root = copyFixture("shop");
  const file = path.join(root, "src/orders/AGENTS.md");
  fs.writeFileSync(file, "# Orders\n\nHuman text.\n\n<!-- archflow:start — generated by `archflow notes`; edit outside these markers -->\nold section\n<!-- archflow:end -->\n\nMore human text.\n");
  writeNotes(analyze(root, { model: shopModel(), skipGit: true }));
  const notes = fs.readFileSync(file, "utf8");
  assert.ok(notes.startsWith("# Orders\n\nHuman text.\n\n" + NOTES_START));
  assert.ok(notes.endsWith("<!-- cantus:end -->\n\nMore human text.\n"));
  assert.doesNotMatch(notes, /archflow|old section/);
});

test("specialists generated by archflow are regenerated, and the old scope agent removed", () => {
  const root = copyFixture("shop");
  const dir = path.join(root, ".claude", "agents");
  fs.mkdirSync(dir, { recursive: true });
  const legacy = "<!-- Generated by `archflow agents`: regenerate it instead of editing. -->";
  fs.writeFileSync(path.join(dir, "archflow-scope.md"), `---\nname: archflow-scope\n---\n${legacy}\n`);
  fs.writeFileSync(path.join(dir, "block-gone.md"), `---\nname: block-gone\n---\n${legacy}\n`);
  const result = exportClaudeAgents(analyze(root, { model: shopModel(), skipGit: true }));
  assert.deepEqual(result.removed.sort(), [".claude/agents/archflow-scope.md", ".claude/agents/block-gone.md"]);
  assert.ok(fs.existsSync(path.join(dir, "cantus-scope.md")));
});

test("with a root CLAUDE.md, the old archflow section is replaced in the folder AGENTS.md", () => {
  const root = copyFixture("shop");
  fs.writeFileSync(path.join(root, "CLAUDE.md"), "# Shop\n");
  const old = (body) => `<!-- archflow:start — generated by \`archflow notes\`; edit outside these markers -->\n${body}\n<!-- archflow:end -->\n`;
  fs.writeFileSync(path.join(root, "src/pricing/AGENTS.md"), `# Notes: Pricing\n\nConventions, decisions and pitfalls of this block. ArchFlow keeps the section between its markers up to date.\n\n${old("old pricing")}`);
  fs.writeFileSync(path.join(root, "src/orders/AGENTS.md"), `# Orders\n\nHuman text.\n\n${old("old orders")}`);
  writeNotes(analyze(root, { model: shopModel(), skipGit: true }));
  assert.doesNotMatch(fs.readFileSync(path.join(root, "src/pricing/AGENTS.md"), "utf8"), /archflow:start/, "the old section is replaced, not duplicated");
  assert.match(fs.readFileSync(path.join(root, "src/orders/AGENTS.md"), "utf8"), /^# Orders\n\nHuman text\.\n\n<!-- cantus:start/);
  assert.match(fs.readFileSync(path.join(root, "src/orders/AGENTS.md"), "utf8"), /<!-- cantus:start/);
  assert.equal(fs.readFileSync(path.join(root, "src/orders/CLAUDE.md"), "utf8"), "@AGENTS.md\n");
});
