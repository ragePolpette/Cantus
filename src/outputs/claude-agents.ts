import fs from "node:fs";
import path from "node:path";
import type { Analysis } from "../analysis/analyze.js";
import { type ArchModel, type Block, type Group, docsForScope, mcpRule } from "../model/index.js";

const GENERATED_MARK = "<!-- Generated by `cantus agents`: regenerate it instead of editing. -->";
// Agents generated while Cantus was called ArchFlow: still ours, so they are replaced or removed.
const LEGACY_GENERATED_MARK = "<!-- Generated by `archflow agents`: regenerate it instead of editing. -->";
const LEGACY_SCOPE_AGENT = "archflow-scope";
const generated = (text: string) => text.includes(GENERATED_MARK) || text.includes(LEGACY_GENERATED_MARK);

export interface AgentsResult {
  written: string[];
  unchanged: string[];
  removed: string[];
  /** `.claude/agents` did not exist: a Claude Code session already open does not watch it, so it loads these agents only after a restart. */
  createdFolder?: boolean;
  /** `.claude` (or `.claude/agents`) is a link to somewhere outside the project: nothing was written, this says where it leads. */
  blocked?: string;
}

/**
 * Where `.claude` or `.claude/agents` leads when it is a symlink or a junction that points outside the project, else undefined.
 * Worktrees often share `.claude` with the main checkout that way; agents written through it would land in the main
 * checkout, visible to every session of every worktree.
 */
export function agentsFolderOutside(root: string): string | undefined {
  const top = fs.realpathSync.native(root);
  for (const relative of [".claude", path.join(".claude", "agents")]) {
    const folder = path.join(root, relative);
    try {
      if (!fs.lstatSync(folder).isSymbolicLink()) continue;
      const target = fs.realpathSync.native(folder);
      const inside = path.relative(top, target);
      if (inside.startsWith("..") || path.isAbsolute(inside)) return target;
    } catch {
      // not there, or a link that leads nowhere: nothing to protect
    }
  }
  return undefined;
}

/**
 * Writes one Claude Code subagent per block to `.claude/agents/`. Each agent fetches its
 * briefing from the Cantus MCP server when it starts, so it never works from a stale copy.
 * Agent files of blocks that no longer exist are removed (only files Cantus generated).
 */
export function exportClaudeAgents(analysis: Analysis, model?: ArchModel): AgentsResult {
  const dir = path.join(analysis.root, ".claude", "agents");
  const outside = agentsFolderOutside(analysis.root);
  if (outside) return { written: [], unchanged: [], removed: [], blocked: outside };
  const createdFolder = !fs.existsSync(dir);
  fs.mkdirSync(dir, { recursive: true });
  const result: AgentsResult = { written: [], unchanged: [], removed: [], ...(createdFolder ? { createdFolder } : {}) };
  const expected = new Set<string>();
  const write = (name: string, content: string) => {
    const file = path.join(dir, `${name}.md`);
    expected.add(file);
    const relative = path.relative(analysis.root, file).split(path.sep).join("/");
    if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === content) {
      result.unchanged.push(relative);
      return;
    }
    fs.writeFileSync(file, content);
    result.written.push(relative);
  };

  for (const info of analysis.blocks) write(agentName(info.block.id), agentFile(info.block, agentName(info.block.id), docsLine(model, { id: info.block.id, blocks: [info.block.id] }), mcpFrontmatter(model, info.block.id)));
  const blocks = new Map(analysis.blocks.map((info) => [info.block.id, info.block]));
  for (const group of model?.groups ?? []) write(groupAgentName(group.id), groupAgentFile(group, blocks, docsLine(model, group), mcpFrontmatter(model, group.id)));
  write(SCOPE_AGENT, scopeAgentFile(mcpFrontmatter(model)));

  for (const entry of fs.readdirSync(dir)) {
    const file = path.join(dir, entry);
    const ours = entry.startsWith("block-") || entry.startsWith("group-") || entry === `${SCOPE_AGENT}.md` || entry === `${LEGACY_SCOPE_AGENT}.md`;
    if (!ours || !entry.endsWith(".md") || expected.has(file)) continue;
    if (!generated(fs.readFileSync(file, "utf8"))) continue;
    fs.rmSync(file);
    result.removed.push(path.relative(analysis.root, file).split(path.sep).join("/"));
  }
  return result;
}

/**
 * Brings the subagents up to date with the map, in projects that already use them (some
 * \`block-\` agent generated by Cantus exists): blocks just sketched on the map get their
 * specialist before an agent builds them. Projects without them are left alone.
 */
export function refreshClaudeAgents(analysis: Analysis, model?: ArchModel): AgentsResult | undefined {
  const dir = path.join(analysis.root, ".claude", "agents");
  if (agentsFolderOutside(analysis.root)) return undefined;
  let used = false;
  try {
    used = fs.readdirSync(dir).some((entry) => entry.startsWith("block-") && entry.endsWith(".md") && generated(fs.readFileSync(path.join(dir, entry), "utf8")));
  } catch {
    used = false;
  }
  return used ? exportClaudeAgents(analysis, model) : undefined;
}

export const SCOPE_AGENT = "cantus-scope";

/**
 * Claude Code watches `.claude/agents` for new specialists only if the folder existed when the session started,
 * and only a folder made before the session (not by its start hook) counts: so the map makes it, and a session
 * opened later loads specialists written while it runs (`cantus agents`, a block added on the live map).
 */
export function ensureAgentsFolder(root: string): void {
  if (agentsFolderOutside(root)) return;
  try {
    fs.mkdirSync(path.join(root, ".claude", "agents"), { recursive: true });
  } catch {
    // read-only project: the specialists load at the next session start
  }
}

/**
 * A specialist's instructions without the file around them, for a session that cannot load the agent
 * (one written after it started, in a folder it was not watching): it hands this text to a general-purpose
 * subagent. Undefined when the id is not a block, a group or the scope agent.
 */
export function specialistInstructions(analysis: Analysis, model: ArchModel | undefined, id: string): string | undefined {
  const body = (file: string) => file.slice(file.indexOf(GENERATED_MARK) + GENERATED_MARK.length).trim();
  const blockId = id.replace(/^block-/, "");
  const block = analysis.blocks.find((info) => info.block.id === blockId)?.block;
  if (block) return body(agentFile(block, agentName(block.id), docsLine(model, { id: block.id, blocks: [block.id] }), []));
  const groupId = id.replace(/^group-/, "");
  const group = model?.groups?.find((candidate) => candidate.id === groupId);
  if (group) {
    const blocks = new Map(analysis.blocks.map((info) => [info.block.id, info.block]));
    return body(groupAgentFile(group, blocks, docsLine(model, group), []));
  }
  if (id === SCOPE_AGENT) return body(scopeAgentFile([]));
  return undefined;
}

export function groupAgentName(groupId: string): string {
  return `group-${groupId}`.replace(/[^a-z0-9-]/g, "-");
}

/**
 * The frontmatter line that takes MCP servers away from a specialist (`agent.mcp` in the map). Without
 * one the agent has no `tools` restriction and inherits the session's, the user's MCP servers included.
 */
function mcpFrontmatter(model: ArchModel | undefined, scopeId?: string): string[] {
  const deny = [...(model?.agent?.mcp?.specialists?.deny ?? []), ...(scopeId ? model?.agent?.mcp?.blocks?.[scopeId]?.deny ?? [] : [])];
  const rules = [...new Set(deny.map(mcpRule))];
  return rules.length ? [`disallowedTools: ${rules.join(", ")}`] : [];
}

/** The team's documents for a scope, for agents working without the MCP server. */
function docsLine(model: ArchModel | undefined, scope: { id: string; blocks: string[] }): string[] {
  const { common, assigned } = docsForScope(model, scope);
  const all = [...assigned, ...common];
  if (all.length === 0) return [];
  return [`The team's notes for you are part of that briefing: ${all.map((doc) => `\`${doc.path}\``).join(", ")}. Follow them over what the code alone suggests; if you work without the MCP server, read them first.`];
}

function groupAgentFile(group: Group, blocks: Map<string, Block>, docs: string[], front: string[]): string {
  const members = group.blocks.map((id) => blocks.get(id)).filter((block): block is Block => !!block);
  const summary = group.description ? `: ${group.description.split("\n")[0].replace(/\.+$/, "")}` : "";
  const description = `Specialist of the ${group.name} group of blocks (${group.blocks.join(", ")})${summary}. Delegate work that spans those blocks to it.`;
  return [
    "---",
    `name: ${groupAgentName(group.id)}`,
    `description: ${JSON.stringify(description)}`,
    ...front,
    "---",
    GENERATED_MARK,
    "",
    `You are the specialist of the **${group.name}** group (\`${group.id}\`): these blocks are one working scope for you.`,
    ...(group.description ? ["", group.description] : []),
    "",
    ...members.map((block) => `- ${block.name} (\`${block.id}\`, ${block.layer}): ${block.include.map((prefix) => `\`${prefix}\``).join(", ")}`),
    "",
    "How to work:",
    "",
    `1. Start with the Cantus MCP tool \`block_context\` with group \`${group.id}\`: the group's internal dependencies, the APIs it uses from outside, and who calls it from outside. (Without the MCP server, run \`cantus context --group ${group.id}\`.)${docs.length ? ` ${docs[0]}` : ""}`,
    "2. Changes across the group's blocks are part of your task. Outside the group, do only what is needed and state exactly what other blocks must provide.",
    "3. Before writing a helper, call `find_api`. Before changing or removing an export used outside the group, call `callers` and update those call sites or keep the old form working.",
    "4. Finish with a short report: files changed per block, exported API added or changed (exact signatures), call sites updated, anything left for other blocks.",
    "",
  ].join("\n");
}

function scopeAgentFile(front: string[]): string {
  const description = "Works on several blocks of the Cantus map as one scope, when no saved group fits. Delegate work that spans a few blocks to it and name the block ids in the task.";
  return [
    "---",
    `name: ${SCOPE_AGENT}`,
    `description: ${JSON.stringify(description)}`,
    ...front,
    "---",
    GENERATED_MARK,
    "",
    "Your scope is the set of blocks named in the task you receive. If the task does not name them, use the Cantus MCP tool `map` and pick the smallest set of blocks the task needs, then say which ones you chose.",
    "",
    "How to work:",
    "",
    "1. Call the Cantus MCP tool `block_context` with `blocks` set to those block ids: you get one briefing for the whole scope (internal dependencies, APIs used from outside, callers from outside).",
    "2. Changes across the blocks of your scope are part of your task. Outside it, do only what is needed and state exactly what other blocks must provide.",
    "3. Before writing a helper, call `find_api`. Before changing or removing an export used outside your scope, call `callers` and update those call sites or keep the old form working.",
    "4. Finish with a short report: files changed per block, exported API added or changed (exact signatures), call sites updated, anything left for other blocks. If this scope is likely to come back, suggest saving it with `save_group`.",
    "",
  ].join("\n");
}

export function agentName(blockId: string): string {
  return `block-${blockId}`.replace(/[^a-z0-9-]/g, "-");
}

function agentFile(block: Block, name: string, docs: string[], front: string[]): string {
  const paths = block.include.map((prefix) => `\`${prefix}\``).join(", ");
  const summary = block.description ? `: ${block.description.split("\n")[0].replace(/\.+$/, "")}` : "";
  const description = `Specialist of the ${block.name} block (${block.include.join(", ")})${summary}. Delegate work inside those paths, or questions about that code, to it.`;
  return [
    "---",
    `name: ${name}`,
    `description: ${JSON.stringify(description)}`,
    ...front,
    "---",
    GENERATED_MARK,
    "",
    `You are the specialist of the **${block.name}** block (\`${block.id}\`, ${block.layer}) of this project. Its files: ${paths}.`,
    ...(block.description ? ["", block.description] : []),
    "",
    "How to work:",
    "",
    `1. Start with the Cantus MCP tool \`block_context\` for block \`${block.id}\`: the API this block uses, the other blocks, and who calls this block's exports. (Without the MCP server, run \`cantus context ${block.id}\`.) Notes in this block's folder (AGENTS.md or CLAUDE.md) load when you open files there.${docs.length ? ` ${docs[0]}` : ""}`,
    `2. Keep your changes inside ${paths}. If the task needs changes in another block, do the part that belongs here and state exactly what the other block must provide (the signature).`,
    "3. Before writing a helper, call `find_api`: it may already exist in another block.",
    "4. Before changing or removing an export, call `callers`, and update those call sites in the same change or keep the old form working.",
    "5. Finish with a short report: files changed, exported API added or changed (exact signatures), call sites updated, and anything left for other blocks.",
    "",
  ].join("\n");
}
