import { writePath } from "../model/write-path.js";
import fs from "node:fs";
import path from "node:path";
import type { Analysis } from "../analysis/analyze.js";
import { type ArchModel, type Block, docsForScope, renderBlockNotes } from "../model/index.js";

export const NOTES_START = "<!-- cantus:start — generated by `cantus notes`; edit outside these markers -->";
export const NOTES_END = "<!-- cantus:end -->";
// Markers written while Cantus was called ArchFlow: their section is replaced, not duplicated.
const LEGACY_NOTES_START = /<!-- archflow:start\b[^\n]*-->/;
const LEGACY_NOTES_END = "<!-- archflow:end -->";

export interface NotesResult {
  written: string[];
  /** Of `written`, the files that did not exist before. */
  created: string[];
  /** Notes files Cantus deleted because nothing but its own text was left in them. */
  removed: string[];
  unchanged: string[];
  /** Blocks without a directory of their own (single files or the project root). */
  skipped: string[];
}

const BLOCK_HEADER = (name: string, product = "Cantus") => `# Notes: ${name}\n\nConventions, decisions and pitfalls of this block. ${product} keeps the section between its markers up to date.\n`;

/**
 * Writes a short, generated section into each block's AGENTS.md (only the blocks in `only`, if given), and a pointer in the project
 * root. One file holds a block's notes: its AGENTS.md, which Codex reads, or the folder's own CLAUDE.md when it has one with text of
 * its own. Claude Code skips every AGENTS.md of a project whose root has a CLAUDE.md, so there each block folder gets a CLAUDE.md
 * that only says `@AGENTS.md`: the notes stay in one place and both tools load them.
 * Coding CLIs load these files only when they work in that folder, so each block's knowledge
 * stays out of the root instructions.
 */
export function writeNotes(analysis: Analysis, model?: ArchModel, options: { only?: string[] } = {}): NotesResult {
  const result: NotesResult = { written: [], created: [], removed: [], unchanged: [], skipped: [] };
  const claudeAtRoot = hasRootClaude(analysis.root);
  for (const info of analysis.blocks) {
    if (options.only && !options.only.includes(info.block.id)) continue;
    const dir = blockDirectory(analysis.root, info.block);
    if (!dir) {
      result.skipped.push(info.block.id);
      continue;
    }
    const headers = [BLOCK_HEADER(info.block.name), BLOCK_HEADER(info.block.name, "ArchFlow")];
    const claude = path.join(dir, "CLAUDE.md");
    const agents = path.join(dir, "AGENTS.md");
    const own = fs.existsSync(path.join(analysis.root, claude)) ? ownedByCantus(path.join(analysis.root, claude)) : undefined;
    if (own === "human") {
      // The folder's CLAUDE.md has text of its own: the notes go in it, and leave an AGENTS.md they used to be in.
      upsert(analysis.root, claude, BLOCK_HEADER(info.block.name), blockSection(analysis, info.block.id, model), result);
      removeSection(analysis.root, agents, headers, result);
      continue;
    }
    upsert(analysis.root, agents, BLOCK_HEADER(info.block.name), blockSection(analysis, info.block.id, model), result);
    if (own === "generated") removeSection(analysis.root, claude, headers, result);
    if (claudeAtRoot) writeStub(analysis.root, claude, result);
  }
  upsert(analysis.root, notesFile(analysis.root, "."), `# ${analysis.name}\n`, rootSection(analysis, model), result);
  return result;
}

const STUB = "@AGENTS.md";

/** A CLAUDE.md that only imports the AGENTS.md next to it. */
function isStub(text: string): boolean {
  return text.replace(/<!--[\s\S]*?-->/g, "").trim() === STUB;
}

/** What a folder's CLAUDE.md is: Cantus's import line, notes Cantus generated alone (an older run put them here), or a person's file. */
function ownedByCantus(file: string): "stub" | "generated" | "human" {
  const text = fs.readFileSync(file, "utf8");
  if (isStub(text)) return "stub";
  const found = generatedSection(text);
  if (!found) return "human";
  const rest = `${text.slice(0, found.start)}${text.slice(found.end)}`.trim();
  return rest === "" || isOnlyHeader(rest) ? "generated" : "human";
}

/** The `# Notes: …` heading Cantus (or ArchFlow) puts above its section, and nothing else. */
function isOnlyHeader(text: string): boolean {
  return /^# Notes: [^\n]*\n+Conventions, decisions and pitfalls of this block\. (?:Cantus|ArchFlow) keeps the section between its markers up to date\.$/.test(text.trim());
}

/** Creates (or turns the generated notes of an older run into) the CLAUDE.md that imports the folder's AGENTS.md. */
function writeStub(root: string, relative: string, result: NotesResult) {
  const file = writePath(root, relative);
  if (fs.existsSync(file)) {
    if (!isStub(fs.readFileSync(file, "utf8"))) return;
  } else {
    fs.writeFileSync(file, `${STUB}\n`);
    const posix = relative.split(path.sep).join("/");
    result.written.push(posix);
    result.created.push(posix);
    return;
  }
  result.unchanged.push(relative.split(path.sep).join("/"));
}

function hasRootClaude(root: string): boolean {
  // Any of these at the root makes Claude Code skip every AGENTS.md of the project.
  return ["CLAUDE.md", path.join(".claude", "CLAUDE.md"), "CLAUDE.local.md"].some((name) => fs.existsSync(path.join(root, name)));
}

function blockDirectory(root: string, block: Block): string | undefined {
  const dir = block.include.find((prefix) => prefix !== "." && prefix !== "" && fs.existsSync(path.join(root, prefix)) && fs.statSync(path.join(root, prefix)).isDirectory());
  return dir?.replace(/\/+$/, "");
}

/** Where the root pointer goes: the root CLAUDE.md if the project has one (Claude Code reads that, not AGENTS.md), else AGENTS.md. */
function notesFile(root: string, dir: string): string {
  const claude = path.join(dir, "CLAUDE.md");
  if (fs.existsSync(path.join(root, claude))) return claude;
  return hasRootClaude(root) ? claude : path.join(dir, "AGENTS.md");
}

/** Takes Cantus's section out of a notes file it no longer writes; deletes the file if nothing else is left. */
function removeSection(root: string, relative: string, headers: string[], result: NotesResult) {
  const file = writePath(root, relative);
  if (!fs.existsSync(file)) return;
  const current = fs.readFileSync(file, "utf8");
  const found = generatedSection(current);
  if (!found) return;
  const rest = `${current.slice(0, found.start).trimEnd()}\n\n${current.slice(found.end).trimStart()}`.trim();
  const posix = relative.split(path.sep).join("/");
  if (rest === "" || isOnlyHeader(rest) || headers.some((header) => rest === header.trim())) {
    fs.rmSync(file);
    result.removed.push(posix);
  } else {
    fs.writeFileSync(file, `${rest}\n`);
    result.written.push(posix);
  }
}

/** "3 updated (a, b, c), 1 created (d)": what a run did to the notes files, existing ones apart from new ones. */
export function describeNotes(result: NotesResult): string {
  const created = result.created;
  const updated = result.written.filter((file) => !created.includes(file));
  const list = (files: string[]) => (files.length > 6 ? `${files.slice(0, 6).join(", ")}, …` : files.join(", "));
  const parts = [`${updated.length} updated${updated.length ? ` (${list(updated)})` : ""}`, `${created.length} created${created.length ? ` (${list(created)})` : ""}`];
  const removed = result.removed ?? [];
  if (removed.length) parts.push(`${removed.length} removed, nothing but Cantus's own text was left in ${removed.length === 1 ? "it" : "them"} (${list(removed)})`);
  return parts.join(", ");
}

/** Where the generated section sits in a notes file, markers included: Cantus's, or ArchFlow's from before the rename. */
function generatedSection(text: string): { start: number; end: number } | undefined {
  const start = text.indexOf(NOTES_START);
  const end = text.indexOf(NOTES_END);
  if (start >= 0 && end > start) return { start, end: end + NOTES_END.length };
  const legacyStart = text.search(LEGACY_NOTES_START);
  const legacyEnd = text.indexOf(LEGACY_NOTES_END);
  if (legacyStart >= 0 && legacyEnd > legacyStart) return { start: legacyStart, end: legacyEnd + LEGACY_NOTES_END.length };
  return undefined;
}

function upsert(root: string, relative: string, header: string, section: string, result: NotesResult) {
  const file = writePath(root, relative);
  const block = `${NOTES_START}\n${section.trimEnd()}\n${NOTES_END}`;
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : undefined;
  let next: string;
  if (current === undefined) {
    next = `${header}\n${block}\n`;
  } else {
    const found = generatedSection(current);
    next = found ? current.slice(0, found.start) + block + current.slice(found.end) : `${current.trimEnd()}\n\n${block}\n`;
  }
  const posix = relative.split(path.sep).join("/");
  if (next === current) {
    result.unchanged.push(posix);
    return;
  }
  fs.writeFileSync(file, next);
  result.written.push(posix);
  if (current === undefined) result.created.push(posix);
}

/** Names listed for one arrow in a block's notes. */
const SYMBOLS_PER_ARROW = 5;
/** Arrows listed in each direction. */
const ARROWS_LISTED = 12;
const more = (total: number) => (total > ARROWS_LISTED ? `; … +${total - ARROWS_LISTED} more blocks` : "");

function blockSection(analysis: Analysis, blockId: string, model?: ArchModel): string {
  const info = analysis.blocks.find((candidate) => candidate.block.id === blockId)!;
  const name = (id: string) => analysis.blocks.find((candidate) => candidate.block.id === id)?.block.name ?? id;
  const { block } = info;
  const uses = analysis.dependencies.filter((dep) => dep.from === blockId);
  const usedBy = analysis.dependencies.filter((dep) => dep.to === blockId);
  const callers = analysis.callSites.filter((site) => site.targetBlock === blockId && site.block !== blockId);
  const counts = new Map<string, number>();
  for (const site of callers) counts.set(site.symbol, (counts.get(site.symbol) ?? 0) + 1);
  const mostUsed = [...counts.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).slice(0, 5);
  // Claude Code loads this file whole when it reads anything in the folder: a block with hundreds of exports used by others
  // must not put all their names there (`block_context` has them).
  const names = (symbols: string[]) => (symbols.length > SYMBOLS_PER_ARROW ? `${symbols.slice(0, SYMBOLS_PER_ARROW).join(", ")}, … +${symbols.length - SYMBOLS_PER_ARROW} more` : symbols.join(", "));

  const lines = [`## Block \`${block.id}\` — ${block.name} (${block.layer})`, ""];
  if (block.description) lines.push(block.description, "");
  if (block.notes?.length) lines.push(...renderBlockNotes(block.notes), "");
  lines.push(`- Files: ${info.files.length}, under ${block.include.map((p) => `\`${p}\``).join(", ")}.`);
  lines.push(`- Uses: ${uses.length ? uses.slice(0, ARROWS_LISTED).map((dep) => `${name(dep.to)} (\`${dep.to}\`: ${names(dep.symbols)})`).join("; ") + more(uses.length) : "no other block"}.`);
  lines.push(`- Used by: ${usedBy.length ? usedBy.slice(0, ARROWS_LISTED).map((dep) => `${name(dep.from)} (\`${dep.from}\`: ${names(dep.symbols)})`).join("; ") + more(usedBy.length) : "no other block"}.`);
  if (mostUsed.length) lines.push(`- Most called from other blocks: ${mostUsed.map(([symbol, count]) => `\`${symbol}\` (${count})`).join(", ")}. Check their callers before changing a signature.`);
  const { common, assigned } = docsForScope(model, { id: block.id, blocks: [block.id] });
  const describe = (docs: typeof assigned) => docs.map((doc) => `\`${doc.path}\`${doc.description ? ` (${doc.description})` : ""}`).join(", ");
  if (assigned.length) lines.push(`- Read before working here: ${describe(assigned)}.`);
  if (common.length) lines.push(`- Shared notes for the whole project: ${describe(common)}.`);
  lines.push(
    "",
    `With the Cantus MCP server: \`block_context\` (block \`${block.id}\`) for this block's full briefing, \`callers\` before changing an export, \`find_api\` before writing a helper that may already exist elsewhere.`,
  );
  return lines.join("\n");
}

/** Up to this many blocks the root pointer lists them all. */
const ROOT_LIST_LIMIT = 15;

function rootSection(analysis: Analysis, model?: ArchModel): string {
  const lines = [
    "## Project map (Cantus)",
    "",
    `This project is split into ${analysis.blocks.length} blocks. Each block folder has its own notes (AGENTS.md, or CLAUDE.md), loaded when you work there. With the Cantus MCP server, start from \`map\`, then \`block_context\` for the block you work on.`,
    "",
  ];
  // This file is loaded in every session: a long list of blocks would cost context each time and grow with the map.
  if (analysis.blocks.length <= ROOT_LIST_LIMIT) {
    for (const info of analysis.blocks) {
      const description = info.block.description ? ` — ${info.block.description.split("\n")[0]}` : "";
      lines.push(`- \`${info.block.id}\` (${info.block.layer}): ${info.block.include.join(", ")}${description}`);
    }
  } else {
    lines.push(`The list of blocks is not repeated here (more than ${ROOT_LIST_LIMIT}): \`map\` shows it, or \`cantus check\` in a terminal.`);
  }
  const common = (model?.docs ?? []).filter((doc) => doc.common);
  if (common.length) {
    lines.push("", "Shared notes for every agent (also included in every `block_context` briefing):", "");
    for (const doc of common) lines.push(`- \`${doc.path}\`${doc.description ? ` — ${doc.description}` : ""}`);
  }
  if (model?.groups?.length) {
    lines.push("", "Groups (blocks worked on together; `block_context` with the group, or the `group-<id>` specialist):", "");
    for (const group of model.groups) lines.push(`- \`${group.id}\` (${group.name}): ${group.blocks.join(", ")}`);
  }
  return lines.join("\n");
}
